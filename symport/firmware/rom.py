"""Core ROM image (ROMBUILD ``TRomHeader`` layout) directory reader.

Layout follows the public ``e32rom.h`` structures as used by the RomBrowser tool: a 128-byte jump
area, then ``iVersion``, ``iTime``, ``iRomBase``, ``iRomSize`` and ``iRomRootDirectoryList``; a root
list ``{count, hwVariant, addressLin}``; directories ``{size, entries...}`` of ``TRomEntry``
``{size, addressLin, attributes, nameLength, UTF-16 name}`` aligned to 4 bytes.

EXPERIMENTAL: verified only against synthetic images generated by SymPort's tests. Nokia firmware
containers (FPSX/VPL) and ROFS images are NOT decoded; unpack them first with a dedicated tool.
"""
from __future__ import annotations

import hashlib
import struct

MAX_ENTRIES = 200_000
MAX_DEPTH = 32
ATT_DIR = 0x10


class RomError(ValueError):
    pass


class RomImage:
    def __init__(self, data):
        self.data = data
        if len(data) < 0x200:
            raise RomError("image too small for a ROM header")
        self.base, self.size, self.root_list = struct.unpack_from("<III", data, 140)
        self.version = struct.unpack_from("<BBH", data, 128)
        if self.size == 0 or self.size > len(data) + 0x1000 or self.base % 0x1000 or self.base == 0:
            raise RomError("ROM header fields are implausible (not a core ROM image or unsupported container)")
        if not self._inside(self.root_list, 12):
            raise RomError("root directory list outside the image")

    def _inside(self, address: int, length: int) -> bool:
        offset = address - self.base
        return address >= self.base and offset + length <= len(self.data)

    def _u32(self, address: int) -> int:
        if not self._inside(address, 4):
            raise RomError("ROM pointer outside the image")
        return struct.unpack_from("<I", self.data, address - self.base)[0]

    def read(self, address: int, length: int) -> bytes:
        if length < 0 or not self._inside(address, length):
            raise RomError("ROM data outside the image")
        offset = address - self.base
        return bytes(self.data[offset:offset + length])

    def entries(self):
        """Yield ``(path, address, size)`` for every file; raises RomError on structural damage."""
        count = self._u32(self.root_list)
        if count == 0 or count > 8:
            raise RomError("implausible root directory count")
        root = self._u32(self.root_list + 8)
        seen = set()
        produced = 0

        def walk(address, prefix, depth):
            nonlocal produced
            if depth > MAX_DEPTH or address in seen:
                raise RomError("directory loop or nesting too deep")
            seen.add(address)
            span = self._u32(address)
            if span > len(self.data):
                raise RomError("directory size outside the image")
            position, end = address + 4, address + 4 + span
            while position + 10 <= end:
                size, target = struct.unpack("<II", self.read(position, 8))
                attributes, name_length = self.read(position + 8, 2)
                if name_length == 0 or position + 10 + 2 * name_length > end + 3:
                    raise RomError("directory entry is damaged")
                name = self.read(position + 10, 2 * name_length).decode("utf-16-le", errors="replace")
                position += 10 + 2 * name_length
                position = (position + 3) & ~3
                if "/" in name or "\\" in name or name in (".", ".."):
                    raise RomError("unsafe entry name")
                produced += 1
                if produced > MAX_ENTRIES:
                    raise RomError("too many ROM entries")
                path = prefix + name
                if attributes & ATT_DIR:
                    yield from walk(target, path + "/", depth + 1)
                else:
                    yield path, target, size

        yield from walk(root, "", 0)

    def file(self, address: int, size: int) -> bytes:
        return self.read(address, size)

    def sha256(self, address: int, size: int) -> str:
        return hashlib.sha256(self.read(address, size)).hexdigest()
